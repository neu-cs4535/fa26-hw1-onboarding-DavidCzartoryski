-- A class member sees a group if they are staff, or if they can see at least one column in it.
-- The inner query runs under gradebook_columns' own RLS, so "can see a column" means exactly
-- what it means for columns (including the instructor_only / released rule), with no second
-- copy of that rule to drift. (SELECT auth.uid()) is evaluated once per statement.
CREATE POLICY "everyone in class can view"
ON public.gradebook_column_groups
AS PERMISSIVE
FOR SELECT
TO authenticated
USING (
  EXISTS (
    SELECT 1
    FROM public.user_privileges up
    WHERE up.user_id = (SELECT auth.uid())
      AND up.class_id = gradebook_column_groups.class_id
  )
  AND (
    EXISTS (
      SELECT 1
      FROM public.user_privileges up2
      WHERE up2.user_id = (SELECT auth.uid())
        AND up2.class_id = gradebook_column_groups.class_id
        AND up2.role IN ('instructor', 'grader')
    )
    OR EXISTS (
      SELECT 1
      FROM public.gradebook_columns gc
      WHERE gc.group_id = gradebook_column_groups.id
    )
  )
);

-- Realtime: staff channel only. A group hidden by the policy above is not pushed to students
-- either. Students pick up group changes on their next load through RLS.
