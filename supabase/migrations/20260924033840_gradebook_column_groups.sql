  AFTER UPDATE OF group_id OR DELETE ON public.gradebook_columns
  FOR EACH ROW
  WHEN (OLD.group_id IS NOT NULL)
  EXECUTE FUNCTION public.gradebook_column_groups_drop_empty();

-- The other direction: a group has to have a column by the time the transaction that created it
-- commits. Deferred, because a group is always created first and given its columns after.
CREATE OR REPLACE FUNCTION public.gradebook_column_groups_require_member()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM public.gradebook_column_groups WHERE id = NEW.id)
     AND NOT EXISTS (SELECT 1 FROM public.gradebook_columns WHERE group_id = NEW.id) THEN
    RAISE EXCEPTION 'Column group "%" has no columns', NEW.name
      USING ERRCODE = 'check_violation',
            HINT = 'Create a group together with its columns (gradebook_column_group_create).';
  END IF;
  RETURN NULL;
END;
$$;

