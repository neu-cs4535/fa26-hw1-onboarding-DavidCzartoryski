-- The render-time heuristic's prefix: "assignment-<type>" for assignment-<type>-*, otherwise
-- everything before the first "-", or "other" for an empty slug. One departure (F8): the
-- heuristic put every two-part assignment slug (the assignment trigger's "assignment-<slug>" for
-- an assignment slug with no "-") into one "assignment" family, so "assignment-hw1" grouped with
-- "assignment-final". Here the assignment's own slug, minus a trailing number, is the type:
-- "assignment-hw1" and "assignment-hw2" are family "assignment-hw", "assignment-final" is
-- "assignment-final".
CREATE OR REPLACE FUNCTION public.gradebook_column_family(p_slug text)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
  SELECT CASE
    WHEN split_part(p_slug, '-', 1) = 'assignment' AND cardinality(string_to_array(p_slug, '-')) >= 3
      THEN 'assignment-' || split_part(p_slug, '-', 2)
    WHEN split_part(p_slug, '-', 1) = 'assignment' AND cardinality(string_to_array(p_slug, '-')) = 2
         AND regexp_replace(split_part(p_slug, '-', 2), '[0-9]+$', '') <> ''
      THEN 'assignment-' || regexp_replace(split_part(p_slug, '-', 2), '[0-9]+$', '')
    ELSE COALESCE(NULLIF(split_part(p_slug, '-', 1), ''), 'other')
  END;
$$;

-- A column's display name without a trailing "(...)" or number: "Lab 1 (Group)" -> "Lab",
-- "Skill #12" -> "Skill", "AI Usage Log 2" -> "AI Usage Log".
CREATE OR REPLACE FUNCTION public.gradebook_column_name_stem(p_name text)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
  SELECT public.gradebook_column_group_clean_name(
    regexp_replace(regexp_replace(p_name, '\s*\([^)]*\)\s*$', ''), '\s*#?\s*\d+\s*$', '')
  );
$$;

-- The heuristic's own title for a family, used when member names don't share a stem.
CREATE OR REPLACE FUNCTION public.gradebook_column_family_title(p_family text)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
  SELECT CASE
    WHEN f = '' OR f = 'other' THEN 'Other'
    WHEN f LIKE 'assignment-%' THEN
      upper(left(split_part(f, '-', 2), 1)) || substr(split_part(f, '-', 2), 2)
    ELSE upper(left(f, 1)) || substr(f, 2)
  END
  FROM (SELECT public.gradebook_column_group_clean_name(p_family) AS f) AS cleaned;
$$;

-- The first free name in a gradebook: p_name if nobody has it (case-insensitively), otherwise
-- "p_name (2)", "p_name (3)", and so on. A blank name becomes "Group".
CREATE OR REPLACE FUNCTION public.gradebook_column_group_free_name(p_gradebook_id bigint, p_name text)
RETURNS text
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_base text := COALESCE(NULLIF(public.gradebook_column_group_clean_name(p_name), ''), 'Group');
  v_candidate text := v_base;
  v_n integer := 1;
BEGIN
  WHILE EXISTS (
    SELECT 1 FROM public.gradebook_column_groups
    WHERE gradebook_id = p_gradebook_id AND lower(name) = lower(v_candidate)
  ) LOOP
    v_n := v_n + 1;
    v_candidate := v_base || ' (' || v_n || ')';
  END LOOP;
  RETURN v_candidate;
END;
$$;

-- The integer column ids in a column's dependencies->'gradebook_columns'. Anything that is not a
-- whole number is skipped rather than allowed to fail a cast.
CREATE OR REPLACE FUNCTION public.gradebook_column_dependency_ids(p_dependencies jsonb)
RETURNS bigint[]
LANGUAGE sql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
  SELECT array_agg(DISTINCT d::bigint ORDER BY d::bigint)
  FROM jsonb_array_elements_text(
    CASE WHEN jsonb_typeof(p_dependencies -> 'gradebook_columns') = 'array'
      THEN p_dependencies -> 'gradebook_columns' END
  ) AS d
  WHERE d ~ '^[0-9]{1,18}$';
$$;

-- ---------------------------------------------------------------------------------------------
-- Default group for a new column
-- ---------------------------------------------------------------------------------------------

-- Applied once, on INSERT, and only when the insert did not say which group it wants. Without it
-- every column created after this migration would be ungrouped, including the ones the
-- assignment trigger creates, which the render-time heuristic used to group as soon as a second
-- one appeared. In order:
--
--   1. Inserted between two members of the same group: join that group ("add Quiz 3 between
--      Quiz 2 and Quiz 4"). Decided by position alone.
--   2. The column just before it is in the same family: join that column's group, or, if that
--      column is ungrouped, create a group for the two of them. This is what keeps a new
--      course's "Assignment 1, Assignment 2, ..." grouped.
--
-- Neither applies to a column computed from the columns it would join: an average of the
-- homework is a summary of the homework group, not one more homework (the backfill's F9).
--
-- Membership is never recomputed afterwards: an UPDATE never runs this, so moving or renaming a
-- column leaves its group alone, and an instructor's choice always wins. The position is worked
-- out here (an unset sort_order means "append"), so this does not depend on firing before or
-- after gradebook_columns_enforce_sort_order_tr.
CREATE OR REPLACE FUNCTION public.gradebook_columns_inherit_group()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_pos integer;
  v_before public.gradebook_columns;
  v_after_group bigint;
  v_class_id bigint;
  v_stem_before text;
  v_stem_new text;
  v_group_id bigint;
  v_deps bigint[] := COALESCE(public.gradebook_column_dependency_ids(NEW.dependencies), '{}');
BEGIN
  IF NEW.group_id IS NOT NULL THEN
    RETURN NEW;
  END IF;

  IF NEW.sort_order IS NOT NULL THEN
    v_pos := GREATEST(NEW.sort_order, 0);
  ELSIF current_setting('pawtograder.bypass_sort_order_trigger_' || NEW.gradebook_id, true) = 'true' THEN
    -- A bulk write that leaves sort_order unset is deciding the layout itself.
    RETURN NEW;
  ELSE
    SELECT COALESCE(max(sort_order), -1) + 1 INTO v_pos
    FROM public.gradebook_columns
    WHERE gradebook_id = NEW.gradebook_id AND id <> NEW.id;
  END IF;

  SELECT * INTO v_before
  FROM public.gradebook_columns
  WHERE gradebook_id = NEW.gradebook_id AND id <> NEW.id AND sort_order < v_pos
  ORDER BY sort_order DESC, id DESC
  LIMIT 1;

  IF v_before.id IS NULL THEN
    RETURN NEW;
  END IF;

  -- 1. Between two members of one group. (Before the sort_order trigger shifts the columns at or
  -- after v_pos, the next one is at v_pos; after, it is at v_pos + 1. Either way it is the first
  -- column at or after v_pos.)
  SELECT group_id INTO v_after_group
  FROM public.gradebook_columns
  WHERE gradebook_id = NEW.gradebook_id AND id <> NEW.id AND sort_order >= v_pos
  ORDER BY sort_order, id
  LIMIT 1;

  -- A summary of the group it would join stays out of it.
  IF v_before.id = ANY (v_deps) OR (
    v_before.group_id IS NOT NULL AND EXISTS (
      SELECT 1 FROM public.gradebook_columns WHERE group_id = v_before.group_id AND id = ANY (v_deps)
    )
  ) THEN
    RETURN NEW;
  END IF;

  IF v_before.group_id IS NOT NULL AND v_before.group_id = v_after_group THEN
    NEW.group_id := v_before.group_id;
    RETURN NEW;
  END IF;

  -- 2. Same family as the column just before it.
  IF public.gradebook_column_family(v_before.slug) IS DISTINCT FROM public.gradebook_column_family(NEW.slug) THEN
    RETURN NEW;
  END IF;

  IF v_before.group_id IS NOT NULL THEN
    NEW.group_id := v_before.group_id;
    RETURN NEW;
  END IF;

  v_stem_before := public.gradebook_column_name_stem(v_before.name);
  v_stem_new := public.gradebook_column_name_stem(NEW.name);

  SELECT class_id INTO v_class_id FROM public.gradebooks WHERE id = NEW.gradebook_id;

  INSERT INTO public.gradebook_column_groups (class_id, gradebook_id, name)
  VALUES (
    v_class_id,
    NEW.gradebook_id,
    public.gradebook_column_group_free_name(
      NEW.gradebook_id,
      CASE
        WHEN v_stem_before = v_stem_new AND v_stem_new <> '' THEN v_stem_new
        ELSE public.gradebook_column_family_title(public.gradebook_column_family(NEW.slug))
      END
    )
  )
  RETURNING id INTO v_group_id;

  UPDATE public.gradebook_columns SET group_id = v_group_id WHERE id = v_before.id;
  NEW.group_id := v_group_id;
  RETURN NEW;
END;
$$;

CREATE TRIGGER gradebook_columns_inherit_group_tr
  BEFORE INSERT ON public.gradebook_columns
  FOR EACH ROW
  EXECUTE FUNCTION public.gradebook_columns_inherit_group();

-- ---------------------------------------------------------------------------------------------
-- The two existing functions that rewrite the whole order
-- ---------------------------------------------------------------------------------------------

-- gradebook_columns_reorder: the checks are unchanged from 20260406120000. The write now goes
-- through gradebook_columns_apply_order, so it touches only the rows that move, keeps groups
-- whole, and sends one realtime message per channel instead of one per row per student.
CREATE OR REPLACE FUNCTION public.gradebook_columns_reorder(p_ordered_column_ids bigint[])
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_gradebook_id bigint;
  v_class_id bigint;
  v_expected_count integer;
  v_payload_count integer;
  v_distinct_payload integer;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  v_payload_count := COALESCE(array_length(p_ordered_column_ids, 1), 0);

  IF v_payload_count = 0 THEN
    RETURN;
  END IF;

  SELECT COUNT(DISTINCT x) INTO v_distinct_payload
  FROM unnest(p_ordered_column_ids) AS x;

  IF v_distinct_payload <> v_payload_count THEN
    RAISE EXCEPTION 'Duplicate column IDs in reorder payload';
  END IF;

  SELECT gc.gradebook_id INTO v_gradebook_id
  FROM public.gradebook_columns AS gc
  WHERE gc.id = p_ordered_column_ids[1];

  IF v_gradebook_id IS NULL THEN
    RAISE EXCEPTION 'gradebook column % not found', p_ordered_column_ids[1];
  END IF;

  SELECT class_id INTO v_class_id
  FROM public.gradebooks
  WHERE id = v_gradebook_id;

  IF v_class_id IS NULL THEN
    RAISE EXCEPTION 'gradebook % not found', v_gradebook_id;
  END IF;

  IF NOT public.authorizeforclassinstructor(v_class_id) THEN
    RAISE EXCEPTION 'insufficient permissions: instructor access required for class %', v_class_id;
  END IF;

  -- Single-key form (bigint); the two-key form requires (integer, integer), not (int, bigint).
  -- Same namespace as every other writer of column order, so all of them serialize per gradebook.
  PERFORM pg_advisory_xact_lock(v_gradebook_id);

  SELECT COUNT(*)::integer INTO v_expected_count
  FROM public.gradebook_columns
  WHERE gradebook_id = v_gradebook_id;

  IF v_expected_count <> v_payload_count THEN
    RAISE EXCEPTION 'Payload count (%) does not match gradebook column count (%)', v_payload_count, v_expected_count;
  END IF;

  IF (
    SELECT COUNT(*)::integer
    FROM public.gradebook_columns
    WHERE gradebook_id = v_gradebook_id
      AND id = ANY (p_ordered_column_ids)
  ) <> v_payload_count THEN
    RAISE EXCEPTION 'One or more column IDs do not belong to this gradebook';
  END IF;

  PERFORM public.gradebook_columns_apply_order(v_gradebook_id, p_ordered_column_ids);
END;
$$;

-- gradebook_auto_layout: the layout algorithm is unchanged from 20250811000001. What changed:
--   * It takes the same per-gradebook lock as every other writer of column order (it used a
--     separate two-key lock, so it could interleave with a reorder; the ::int cast in that lock
--     also failed for gradebook ids above 2^31).
--   * Dependency ids that are not whole numbers are skipped instead of failing a cast.
--   * The final pass keeps groups whole, and clients get one realtime message per channel for
--     the columns that actually moved, instead of one per row per student.
CREATE OR REPLACE FUNCTION public.gradebook_auto_layout(p_gradebook_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_col record;
  v_dep_col_id bigint;
  v_max_dep_order integer;
  v_new_order integer;
  v_processed_ids bigint[] := '{}';
  v_remaining_count integer;
  v_prev_remaining_count integer := -1;
  v_class_id bigint;
  v_before jsonb;
  v_moved bigint[];
BEGIN
  SELECT class_id INTO v_class_id
  FROM public.gradebooks
  WHERE id = p_gradebook_id;

  IF v_class_id IS NULL THEN
    RAISE EXCEPTION 'gradebook % not found', p_gradebook_id;
  END IF;

  IF NOT public.authorizeforclassinstructor(v_class_id) THEN
    RAISE EXCEPTION 'insufficient permissions: instructor access required for class %', v_class_id;
  END IF;

  PERFORM pg_advisory_xact_lock(p_gradebook_id);

  SELECT jsonb_object_agg(id, sort_order) INTO v_before
  FROM public.gradebook_columns
  WHERE gradebook_id = p_gradebook_id;

  PERFORM set_config('pawtograder.bypass_sort_order_trigger_' || p_gradebook_id, 'true', true);
  PERFORM set_config('pawtograder.batch_column_broadcast_' || p_gradebook_id, 'true', true);

  -- Step 1: Initial alphanumeric sort by slug (lab-2 before lab-10)
  WITH ordered_cols AS (
    SELECT id, (ROW_NUMBER() OVER (ORDER BY
      regexp_replace(slug, '\d+', '', 'g'),
      COALESCE((regexp_match(slug, '\d+'))[1]::integer, 0),
      slug
    ) - 1)::integer AS temp_sort_order
    FROM public.gradebook_columns
    WHERE gradebook_id = p_gradebook_id
  )
  UPDATE public.gradebook_columns gc
  SET sort_order = oc.temp_sort_order
  FROM ordered_cols oc
  WHERE gc.id = oc.id
    AND gc.sort_order IS DISTINCT FROM oc.temp_sort_order;

  -- Step 2: Topological sort to respect gradebook_column dependencies
  LOOP
    SELECT COUNT(*) INTO v_remaining_count
    FROM public.gradebook_columns
    WHERE gradebook_id = p_gradebook_id
      AND id <> ALL(v_processed_ids);

    EXIT WHEN v_remaining_count = 0;

    IF v_remaining_count = v_prev_remaining_count THEN
      RAISE WARNING 'Circular dependency detected in gradebook %. Stopping topological sort.', p_gradebook_id;
      EXIT;
    END IF;
    v_prev_remaining_count := v_remaining_count;

    FOR v_col IN
      SELECT id, slug, public.gradebook_column_dependency_ids(dependencies) AS dep_ids, sort_order
      FROM public.gradebook_columns
      WHERE gradebook_id = p_gradebook_id
        AND id <> ALL(v_processed_ids)
      ORDER BY sort_order NULLS LAST, id
    LOOP
      IF COALESCE(cardinality(v_col.dep_ids), 0) > 0 THEN

        v_max_dep_order := -1;

        FOREACH v_dep_col_id IN ARRAY v_col.dep_ids
        LOOP
          IF v_dep_col_id = ANY(v_processed_ids) THEN
            SELECT sort_order INTO v_new_order
            FROM public.gradebook_columns
            WHERE id = v_dep_col_id AND gradebook_id = p_gradebook_id;

            IF v_new_order IS NOT NULL AND v_new_order > v_max_dep_order THEN
              v_max_dep_order := v_new_order;
            END IF;
          END IF;
        END LOOP;

        IF EXISTS (
          SELECT 1
          FROM unnest(v_col.dep_ids) AS dep_id
          WHERE dep_id <> ALL(v_processed_ids)
            AND EXISTS (
              SELECT 1 FROM public.gradebook_columns
              WHERE id = dep_id AND gradebook_id = p_gradebook_id
            )
        ) THEN
          CONTINUE;
        END IF;

        IF v_max_dep_order >= 0 THEN
          v_new_order := v_max_dep_order + 1;
          UPDATE public.gradebook_columns
          SET sort_order = v_new_order
          WHERE id = v_col.id;
        END IF;
      END IF;

      v_processed_ids := array_append(v_processed_ids, v_col.id);
    END LOOP;
  END LOOP;

  -- Final pass: compact to 0..n-1 with every group's members adjacent.
  PERFORM public.gradebook_columns_make_groups_contiguous(p_gradebook_id);

  PERFORM set_config('pawtograder.batch_column_broadcast_' || p_gradebook_id, 'false', true);
  PERFORM set_config('pawtograder.bypass_sort_order_trigger_' || p_gradebook_id, 'false', true);

  SELECT array_agg(id ORDER BY id) INTO v_moved
  FROM public.gradebook_columns
  WHERE gradebook_id = p_gradebook_id
    AND sort_order IS DISTINCT FROM (v_before ->> id::text)::integer;

  PERFORM public.gradebook_columns_broadcast_order(p_gradebook_id, v_moved);
END;
$function$;

-- ---------------------------------------------------------------------------------------------
-- Backfill
--
-- Reads slugs, names and dependencies once per gradebook, so nothing has to read them at render
-- time again. It is a function rather than inline SQL for one reason: a gradebook that exists
-- before this migration is backfilled by the migration, but `supabase db reset` replays
-- migrations into an empty database and seeds afterwards, and the seed has to leave its class
-- in the same state a pre-existing course would be in. scripts/DatabaseSeedingUtils.ts calls it
-- once, after it has created its columns. The app never calls it; only service_role can.
--
-- It only touches gradebooks that have no groups yet, so running it twice is a no-op and it
-- can never overwrite a grouping an instructor has since edited.
--
-- It starts from exactly what the render-time heuristic produced and departs from it only where
-- the heuristic was wrong; each departure is labelled (F1, F2, F3, F4, F6, F8, F9) and listed in the PR.
--
--   1. Order each gradebook's columns by (sort_order, id) and give each a position 1..n. A NULL
--      sort_order counts as 0 here, as everywhere, but no longer collides with another column,
--      because position is decided by (sort_order, id) (F6).
--   2. Family = the heuristic's prefix: "assignment-<type>" for assignment-<type>-*, otherwise
--      everything before the first "-".
--   3. A family run is consecutive positions with the same family. The heuristic also cut a run
--      wherever sort_order skipped a value; positions don't, so a hole left by a deleted column
--      no longer splits a family in two (F1). A column computed from other members of its own
--      run is their summary, not their sibling ("final-grade" computed from "final-exam"), so it
--      leaves the run and is treated like any other lone computed column (F9).
--   4. Columns left on their own after step 3 that are computed from exactly the same set of
--      columns, and sit next to each other, form one run (F4).
--   5. Every run of two or more columns becomes a group. A run of one stays ungrouped, which is
--      what it rendered as.
--   6. Name: the common stem of the member columns' display names (minus a trailing "(...)" and
--      number), so "AI Usage Log 1/2" gives "AI Usage Log", not "Ai" (F3). Failing that, the
--      heuristic's own title. A run of computed columns is named after the group its inputs
--      are all in ("Skill summary"), failing that "Summary".
--   7. Names are unique per gradebook: a family interrupted by some other column stays two
--      groups, because merging them would move columns, but the second is "Quiz (2)" and no
--      longer shares the first one's collapse state (F2). Every candidate is checked against
--      every name already taken, including other generated ones.
--
-- Policy for rows it can't classify: none are dropped and none are moved. A column whose slug
-- has no "-" is its own family, exactly as before; anything that ends up alone is ungrouped; a
-- dependency entry that isn't a column id is ignored. The backfill never changes sort_order.
-- ---------------------------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.gradebook_column_groups_backfill(p_gradebook_id bigint DEFAULT NULL)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_created integer := 0;
  v_group record;
  v_group_id bigint;
BEGIN
  -- Qualified with pg_temp throughout: this runs as the table owner, and an unqualified name
  -- would resolve to a public table of the same name first.
  DROP TABLE IF EXISTS pg_temp._gcg_columns, pg_temp._gcg_runs, pg_temp._gcg_groups;

  CREATE TEMP TABLE _gcg_columns AS
  SELECT
    gc.id,
    gc.gradebook_id,
    g.class_id,
    row_number() OVER (PARTITION BY gc.gradebook_id ORDER BY COALESCE(gc.sort_order, 0), gc.id) AS pos,
    public.gradebook_column_family(gc.slug) AS family,
    public.gradebook_column_dependency_ids(gc.dependencies) AS deps,
    public.gradebook_column_name_stem(gc.name) AS stem
  FROM public.gradebook_columns gc
  JOIN public.gradebooks g ON g.id = gc.gradebook_id
  WHERE (p_gradebook_id IS NULL OR gc.gradebook_id = p_gradebook_id)
    AND NOT EXISTS (SELECT 1 FROM public.gradebook_column_groups x WHERE x.gradebook_id = gc.gradebook_id);

  -- Step 3, first pass: family runs by position, then take out every column that is computed
  -- from another member of its own run (it becomes a family of its own).
  WITH first_runs AS (
    SELECT
      x.id,
      x.gradebook_id,
      sum(CASE WHEN x.family IS DISTINCT FROM x.prev_family THEN 1 ELSE 0 END)
        OVER (PARTITION BY x.gradebook_id ORDER BY x.pos) AS family_run
    FROM (
      SELECT c.*, lag(c.family) OVER (PARTITION BY c.gradebook_id ORDER BY c.pos) AS prev_family
      FROM pg_temp._gcg_columns c
    ) x
  ),
  summaries AS (
    SELECT DISTINCT c.id
    FROM pg_temp._gcg_columns c
    JOIN first_runs fr ON fr.id = c.id
    JOIN first_runs sib ON sib.gradebook_id = fr.gradebook_id AND sib.family_run = fr.family_run AND sib.id <> c.id
    WHERE sib.id = ANY (c.deps)
  )
  UPDATE pg_temp._gcg_columns c
  SET family = 'summary:' || c.id
  FROM summaries s
  WHERE s.id = c.id;

  -- Steps 3 and 4. A unit is a family run (if it has 2+ members), a set of inputs (for a lone
  -- computed column), or the column itself; consecutive columns with the same unit key are a run.
  CREATE TEMP TABLE _gcg_runs AS
  WITH family_runs AS (
    SELECT
      x.*,
      sum(CASE WHEN x.family IS DISTINCT FROM x.prev_family THEN 1 ELSE 0 END)
        OVER (PARTITION BY x.gradebook_id ORDER BY x.pos) AS family_run
    FROM (
      SELECT c.*, lag(c.family) OVER (PARTITION BY c.gradebook_id ORDER BY c.pos) AS prev_family
      FROM pg_temp._gcg_columns c
    ) x
  ),
  units AS (
    SELECT
      fr.*,
      CASE
        WHEN count(*) OVER (PARTITION BY fr.gradebook_id, fr.family_run) > 1 THEN 'family:' || fr.family_run
        WHEN fr.deps IS NOT NULL THEN 'derived:' || fr.deps::text
        ELSE 'column:' || fr.id
      END AS unit_key
    FROM family_runs fr
  ),
  runs AS (
    SELECT
      k.*,
      sum(CASE WHEN k.unit_key IS DISTINCT FROM k.prev_unit_key THEN 1 ELSE 0 END)
        OVER (PARTITION BY k.gradebook_id ORDER BY k.pos) AS run
    FROM (
      SELECT u.*, lag(u.unit_key) OVER (PARTITION BY u.gradebook_id ORDER BY u.pos) AS prev_unit_key
      FROM units u
    ) k
  )
  SELECT r.*, count(*) OVER (PARTITION BY r.gradebook_id, r.run) AS run_size
  FROM runs r;

  -- Steps 5 and 6.
  CREATE TEMP TABLE _gcg_groups AS
  SELECT
    r.gradebook_id,
    min(r.class_id) AS class_id,
    r.run,
    min(r.pos) AS first_pos,
    bool_or(r.unit_key LIKE 'derived:%') AS is_derived,
    CASE
      WHEN count(DISTINCT r.stem) = 1 AND min(r.stem) <> '' THEN min(r.stem)
      ELSE public.gradebook_column_family_title(min(r.family))
    END AS name,
    NULL::bigint AS group_id
  FROM pg_temp._gcg_runs r
  WHERE r.run_size > 1
  GROUP BY r.gradebook_id, r.run;

  -- A run of computed columns is named after the one non-derived group all of its inputs are in.
  UPDATE pg_temp._gcg_groups dg
  SET name = COALESCE(
    (
      SELECT src.name || ' summary'
      FROM pg_temp._gcg_runs m
      CROSS JOIN LATERAL unnest(m.deps) AS dep(id)
      JOIN pg_temp._gcg_runs d ON d.id = dep.id
      JOIN pg_temp._gcg_groups src ON src.gradebook_id = d.gradebook_id AND src.run = d.run AND NOT src.is_derived
      WHERE m.gradebook_id = dg.gradebook_id AND m.run = dg.run
      GROUP BY src.name
      HAVING count(*) = (
        SELECT count(*) FROM pg_temp._gcg_runs m2 CROSS JOIN LATERAL unnest(m2.deps)
        WHERE m2.gradebook_id = dg.gradebook_id AND m2.run = dg.run
      )
    ),
    'Summary'
  )
  WHERE dg.is_derived;

  -- Step 7, one group at a time in left-to-right order, so every name is checked against every
  -- name taken before it.
  FOR v_group IN
    SELECT gradebook_id, class_id, run, name FROM pg_temp._gcg_groups ORDER BY gradebook_id, first_pos
  LOOP
    INSERT INTO public.gradebook_column_groups (class_id, gradebook_id, name)
    VALUES (
      v_group.class_id,
      v_group.gradebook_id,
      public.gradebook_column_group_free_name(v_group.gradebook_id, v_group.name)
    )
    RETURNING id INTO v_group_id;

    UPDATE pg_temp._gcg_groups
    SET group_id = v_group_id
    WHERE gradebook_id = v_group.gradebook_id AND run = v_group.run;

    v_created := v_created + 1;
  END LOOP;

  UPDATE public.gradebook_columns gc
  SET group_id = g.group_id
  FROM pg_temp._gcg_runs r
  JOIN pg_temp._gcg_groups g ON g.gradebook_id = r.gradebook_id AND g.run = r.run
  WHERE gc.id = r.id;

  DROP TABLE pg_temp._gcg_columns, pg_temp._gcg_runs, pg_temp._gcg_groups;
  RETURN v_created;
END;
$$;

