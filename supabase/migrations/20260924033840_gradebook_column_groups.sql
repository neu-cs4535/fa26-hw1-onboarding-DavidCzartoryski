  AFTER INSERT ON public.gradebook_column_groups
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW
  EXECUTE FUNCTION public.gradebook_column_groups_require_member();

-- ---------------------------------------------------------------------------------------------
-- Column order: one definition, one way to write it
-- ---------------------------------------------------------------------------------------------

-- Columns in the order the gradebook draws them. Each column belongs to a unit: a whole group
-- ('g' || group_id) or an ungrouped column ('c' || id). Units are ordered by their first column,
-- by (sort_order, id), and a group's columns follow each other in the same order. NULL
-- sort_order counts as 0, as it does in the client (lib/gradebookColumnGroups.ts). Ordering units
-- by their first column's (sort_order, id), rather than by sort_order alone, is what stops a tie
-- between a group and an ungrouped column from interleaving them.
CREATE OR REPLACE FUNCTION public.gradebook_columns_display_order(p_gradebook_id bigint)
RETURNS TABLE (id bigint, group_id bigint, pos bigint, unit text)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT
    a.id,
    a.group_id,
    row_number() OVER (ORDER BY a.anchor_sort, a.anchor_id, a.sort_order, a.id) AS pos,
    a.unit
  FROM (
    SELECT
      c.id,
      c.group_id,
      c.sort_order,
      c.unit,
      first_value(c.sort_order) OVER w AS anchor_sort,
      first_value(c.id) OVER w AS anchor_id
    FROM (
      SELECT
        gc.id,
        gc.group_id,
        COALESCE(gc.sort_order, 0) AS sort_order,
        COALESCE('g' || gc.group_id, 'c' || gc.id) AS unit
      FROM public.gradebook_columns gc
      WHERE gc.gradebook_id = p_gradebook_id
    ) c
    WINDOW w AS (PARTITION BY c.unit ORDER BY c.sort_order, c.id)
  ) a
  ORDER BY pos;
$$;

-- True if some group's members are not next to each other in (sort_order, id) order.
CREATE OR REPLACE FUNCTION public.gradebook_column_groups_torn(p_gradebook_id bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM (
      SELECT group_id, row_number() OVER (ORDER BY COALESCE(sort_order, 0), id) AS rn
      FROM public.gradebook_columns
      WHERE gradebook_id = p_gradebook_id
    ) o
    WHERE o.group_id IS NOT NULL
    GROUP BY o.group_id
    HAVING max(o.rn) - min(o.rn) + 1 <> count(*)
  );
$$;

-- The message for "these columns moved": up to 49 row ids, or a refetch signal for 50 or more.
CREATE OR REPLACE FUNCTION public.gradebook_columns_order_payload(p_class_id bigint, p_column_ids bigint[], p_audience text)
RETURNS jsonb
LANGUAGE sql
STABLE
SET search_path = public, pg_temp
AS $$
  SELECT jsonb_build_object(
    'type', 'table_change',
    'operation', 'UPDATE',
    'table', 'gradebook_columns',
    'class_id', p_class_id,
    'affected_count', cardinality(p_column_ids),
    'target_audience', p_audience,
    'timestamp', now()
  ) || CASE
    WHEN cardinality(p_column_ids) >= 50 THEN jsonb_build_object('requires_refetch', true)
    ELSE jsonb_build_object('row_ids', to_jsonb(p_column_ids), 'requires_refetch', false)
  END;
$$;

-- Tell clients that some columns moved: one message per channel, in the shape of the
-- statement-level broadcasts in 20251102112812_reduce-rt-spam (up to 49 row ids, or a refetch
-- signal for 50 or more). The row-level column broadcast would send every moved row to every
-- student, which for one "move this 100-column group" is 200 rows times the class size. Clients
-- refetch the ids through RLS, so a student is never sent a staff-only column's data.
CREATE OR REPLACE FUNCTION public.gradebook_columns_broadcast_order(p_gradebook_id bigint, p_column_ids bigint[])
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_class_id bigint;
  v_student_ids bigint[];
  v_student_payload jsonb;
  v_profile_id uuid;
BEGIN
  IF COALESCE(cardinality(p_column_ids), 0) = 0 THEN
    RETURN;
  END IF;

  SELECT class_id INTO v_class_id FROM public.gradebooks WHERE id = p_gradebook_id;
  IF v_class_id IS NULL THEN
    RETURN;
  END IF;

  PERFORM public.safe_broadcast(
    public.gradebook_columns_order_payload(v_class_id, p_column_ids, 'staff'),
    'broadcast',
    'class:' || v_class_id || ':staff',
    true
  );

  -- Students hear only about columns they can see (the gradebook_columns RLS rule).
  SELECT array_agg(gc.id ORDER BY gc.id) INTO v_student_ids
  FROM public.gradebook_columns gc
  WHERE gc.id = ANY (p_column_ids)
    AND (COALESCE(gc.instructor_only, false) = false OR gc.released = true);

  IF COALESCE(cardinality(v_student_ids), 0) = 0 THEN
    RETURN;
  END IF;

  v_student_payload := public.gradebook_columns_order_payload(v_class_id, v_student_ids, 'user');
  FOR v_profile_id IN
    SELECT ur.private_profile_id FROM public.user_roles ur WHERE ur.class_id = v_class_id AND ur.role = 'student'
  LOOP
    PERFORM public.safe_broadcast(
      v_student_payload,
      'broadcast',
      'class:' || v_class_id || ':user:' || v_profile_id,
      true
    );
  END LOOP;
END;
$$;

-- The row-level column broadcast, from 20250929004834, with two changes:
--   * Rows written by gradebook_columns_write_order are announced by
--     gradebook_columns_broadcast_order instead (one message per channel).
--   * Students are only sent columns they can see, by the same rule as gradebook_columns' RLS
--     (not instructor_only, or released). It used to send every column, staff-only ones
--     included, to every student's channel. A column that stops being visible (or is deleted
--     while visible) is sent to students as a DELETE carrying only its id.
CREATE OR REPLACE FUNCTION public.broadcast_gradebook_columns_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
    target_class_id BIGINT;
    staff_payload JSONB;
    user_payload JSONB;
    affected_profile_ids UUID[];
    profile_id UUID;
    visible_before BOOLEAN := false;
    visible_after BOOLEAN := false;
BEGIN
    IF TG_OP = 'UPDATE'
       AND current_setting('pawtograder.batch_column_broadcast_' || NEW.gradebook_id, true) = 'true' THEN
        RETURN NEW;
    END IF;

    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        visible_before := COALESCE(OLD.instructor_only, false) = false OR OLD.released = true;
    END IF;
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        visible_after := COALESCE(NEW.instructor_only, false) = false OR NEW.released = true;
    END IF;

    -- Get the class_id from the record
    IF TG_OP = 'INSERT' THEN
        target_class_id := NEW.class_id;
    ELSIF TG_OP = 'UPDATE' THEN
        target_class_id := COALESCE(NEW.class_id, OLD.class_id);
    ELSIF TG_OP = 'DELETE' THEN
        target_class_id := OLD.class_id;
    END IF;

    IF target_class_id IS NOT NULL THEN
        -- Create payload for gradebook_columns changes
        staff_payload := jsonb_build_object(
            'type', 'table_change',
            'operation', TG_OP,
            'table', TG_TABLE_NAME,
            'row_id', CASE
                WHEN TG_OP = 'DELETE' THEN OLD.id
                ELSE NEW.id
            END,
            'data', CASE
                WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD)
                ELSE to_jsonb(NEW)
            END,
            'class_id', target_class_id,
            'target_audience', 'staff',
            'timestamp', NOW()
        );

        -- Broadcast to staff channel (instructors and graders see all column changes)
        PERFORM public.safe_broadcast(
            staff_payload,
            'broadcast',
            'class:' || target_class_id || ':staff',
            true
        );

        IF visible_after THEN
            -- Same as staff but marked for users
            user_payload := staff_payload || jsonb_build_object('target_audience', 'user');
        ELSIF visible_before THEN
            user_payload := jsonb_build_object(
                'type', 'table_change',
                'operation', 'DELETE',
                'table', TG_TABLE_NAME,
                'row_id', CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END,
                'class_id', target_class_id,
                'target_audience', 'user',
                'timestamp', NOW()
            );
        END IF;

        IF user_payload IS NOT NULL THEN
            -- Get all students in the class for user channels
            SELECT ARRAY(
                SELECT ur.private_profile_id
                FROM public.user_roles ur
                WHERE ur.class_id = target_class_id AND ur.role = 'student'
            ) INTO affected_profile_ids;

            FOREACH profile_id IN ARRAY affected_profile_ids
            LOOP
                PERFORM public.safe_broadcast(
                    user_payload,
                    'broadcast',
                    'class:' || target_class_id || ':user:' || profile_id,
                    true
                );
            END LOOP;
        END IF;
    END IF;

    -- Return the appropriate record
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    ELSE
        RETURN NEW;
    END IF;
END;
$function$;

-- Write a left-to-right order (sort_order 0..n-1 in array order), touching only rows whose
-- sort_order changes, and return their ids. Turns off the sort_order trigger's shifting and the
-- row-level broadcast for the duration, and restores both flags to what they were, so callers
-- never have to set them. Does not broadcast: the caller does, once.
CREATE OR REPLACE FUNCTION public.gradebook_columns_write_order(p_gradebook_id bigint, p_ordered_ids bigint[])
RETURNS bigint[]
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_bypass_key text := 'pawtograder.bypass_sort_order_trigger_' || p_gradebook_id;
  v_batch_key text := 'pawtograder.batch_column_broadcast_' || p_gradebook_id;
  v_prev_bypass text := COALESCE(NULLIF(current_setting(v_bypass_key, true), ''), 'false');
  v_prev_batch text := COALESCE(NULLIF(current_setting(v_batch_key, true), ''), 'false');
  v_changed bigint[];
BEGIN
  PERFORM set_config(v_bypass_key, 'true', true);
  PERFORM set_config(v_batch_key, 'true', true);

  WITH updated AS (
    UPDATE public.gradebook_columns gc
    SET sort_order = (t.ord - 1)::integer
    FROM unnest(p_ordered_ids) WITH ORDINALITY AS t(id, ord)
    WHERE gc.id = t.id
      AND gc.gradebook_id = p_gradebook_id
      AND gc.sort_order IS DISTINCT FROM (t.ord - 1)::integer
    RETURNING gc.id
  )
  SELECT COALESCE(array_agg(id), '{}') INTO v_changed FROM updated;

  PERFORM set_config(v_bypass_key, v_prev_bypass, true);
  PERFORM set_config(v_batch_key, v_prev_batch, true);
  RETURN v_changed;
END;
$$;

-- Renumber a gradebook's columns 0..n-1 in display order, so every group's members are adjacent,
-- keeping every other relative order. Never changes membership. Returns the ids it moved.
CREATE OR REPLACE FUNCTION public.gradebook_columns_make_groups_contiguous(p_gradebook_id bigint)
RETURNS bigint[]
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  RETURN public.gradebook_columns_write_order(
    p_gradebook_id,
    (SELECT array_agg(d.id ORDER BY d.pos) FROM public.gradebook_columns_display_order(p_gradebook_id) d)
  );
END;
$$;

-- Write a full left-to-right order, close up any group it split, and tell clients once.
-- Callers check authorization and hold pg_advisory_xact_lock(gradebook_id).
CREATE OR REPLACE FUNCTION public.gradebook_columns_apply_order(p_gradebook_id bigint, p_ordered_ids bigint[])
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_changed bigint[];
BEGIN
  v_changed := public.gradebook_columns_write_order(p_gradebook_id, p_ordered_ids);
  IF public.gradebook_column_groups_torn(p_gradebook_id) THEN
    v_changed := v_changed || public.gradebook_columns_make_groups_contiguous(p_gradebook_id);
  END IF;
  PERFORM public.gradebook_columns_broadcast_order(
    p_gradebook_id,
    ARRAY(SELECT DISTINCT x FROM unnest(v_changed) AS x ORDER BY x)
  );
END;
$$;

-- A write that puts a column into a group (an INSERT with group_id, or an UPDATE that changes
-- it) without going through the RPCs can leave the group split. Repair it after the statement.
-- Skipped while a function is managing the order itself (it holds the sort_order bypass), and
-- for statements nested inside other triggers. Writes that only change sort_order are left to
-- the RPCs: the seed's renumbering splits groups on its way to a layout, and repairing each step
-- would change the layout it arrives at.
CREATE OR REPLACE FUNCTION public.gradebook_columns_repair_group_order()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_gradebook_id bigint;
  v_gradebook_ids bigint[];
BEGIN
  IF pg_trigger_depth() > 1 THEN
    RETURN NULL;
  END IF;

  IF TG_OP = 'INSERT' THEN
    SELECT array_agg(DISTINCT n.gradebook_id) INTO v_gradebook_ids
    FROM new_table n
    WHERE n.group_id IS NOT NULL;
  ELSE
    SELECT array_agg(DISTINCT n.gradebook_id) INTO v_gradebook_ids
    FROM new_table n
    JOIN old_table o ON o.id = n.id
    WHERE n.group_id IS NOT NULL
      AND n.group_id IS DISTINCT FROM o.group_id;
  END IF;

  FOREACH v_gradebook_id IN ARRAY COALESCE(v_gradebook_ids, '{}')
  LOOP
    CONTINUE WHEN current_setting('pawtograder.bypass_sort_order_trigger_' || v_gradebook_id, true) = 'true';
    CONTINUE WHEN NOT public.gradebook_column_groups_torn(v_gradebook_id);
    PERFORM pg_advisory_xact_lock(v_gradebook_id);
    PERFORM public.gradebook_columns_broadcast_order(
      v_gradebook_id,
      public.gradebook_columns_make_groups_contiguous(v_gradebook_id)
    );
  END LOOP;

  RETURN NULL;
END;
$$;

CREATE TRIGGER gradebook_columns_repair_groups_insert_tr
  AFTER INSERT ON public.gradebook_columns
  REFERENCING NEW TABLE AS new_table
  FOR EACH STATEMENT
  EXECUTE FUNCTION public.gradebook_columns_repair_group_order();

CREATE TRIGGER gradebook_columns_repair_groups_update_tr
  AFTER UPDATE ON public.gradebook_columns
  REFERENCING OLD TABLE AS old_table NEW TABLE AS new_table
  FOR EACH STATEMENT
  EXECUTE FUNCTION public.gradebook_columns_repair_group_order();

