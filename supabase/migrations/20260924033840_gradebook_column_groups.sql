-- Gradebook column groups as data.
--
-- Until now a "group" was computed in the browser on every render (the groupedColumns memo in
-- manage/gradebook/gradebookTable.tsx and its copy in gradebook/whatIf.tsx): split the slug on
-- "-", take a prefix, and cut a new group wherever sort_order is not exactly previous + 1. This
-- migration makes a group a row, makes membership a foreign key on the column, and backfills
-- every existing gradebook so it comes out grouped.
--
-- Design, in brief (the PR description has the long form):
--   * A column is in at most one group: gradebook_columns.group_id, nullable. NULL means "not in
--     a group", which renders exactly like a group of one does today (no header).
--   * A group has no position of its own. It sits where its first member sits, and its members
--     are kept contiguous in sort_order by the two RPCs that renumber columns (reorder and
--     auto-layout). One ordering, not two that can disagree.
--   * (gradebook_id, group_id) is a composite foreign key, so a column can only ever point at a
--     group in its own gradebook, and (gradebook_id, class_id) on the group is a composite
--     foreign key to gradebooks, so the class_id that RLS reads is the gradebook's real class.
--   * Group names are unique per gradebook, case-insensitively. The table's collapse state is
--     keyed by group name, and two groups sharing a name used to collapse and expand together.

-- ---------------------------------------------------------------------------------------------
-- Schema
-- ---------------------------------------------------------------------------------------------

-- Target for the composite foreign key below. id is already unique, so this cannot fail.
CREATE UNIQUE INDEX IF NOT EXISTS gradebooks_id_class_id_key ON public.gradebooks (id, class_id);
ALTER TABLE public.gradebooks
  ADD CONSTRAINT gradebooks_id_class_id_key UNIQUE USING INDEX gradebooks_id_class_id_key;

CREATE TABLE public.gradebook_column_groups (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  class_id bigint NOT NULL,
  gradebook_id bigint NOT NULL,
  name text NOT NULL,
  CONSTRAINT gradebook_column_groups_name_not_blank CHECK (length(btrim(name)) > 0),
  CONSTRAINT gradebook_column_groups_gradebook_fkey FOREIGN KEY (gradebook_id, class_id)
    REFERENCES public.gradebooks (id, class_id) ON DELETE CASCADE,
  -- Target for gradebook_columns' composite foreign key.
  CONSTRAINT gradebook_column_groups_gradebook_id_id_key UNIQUE (gradebook_id, id)
);

COMMENT ON TABLE public.gradebook_column_groups IS
  'A named, collapsible run of gradebook columns. Membership lives on gradebook_columns.group_id; a group''s position is its first member''s sort_order.';

CREATE UNIQUE INDEX gradebook_column_groups_gradebook_name_key
  ON public.gradebook_column_groups (gradebook_id, lower(name));
CREATE INDEX gradebook_column_groups_class_id_idx ON public.gradebook_column_groups (class_id);

ALTER TABLE public.gradebook_columns ADD COLUMN group_id bigint;

COMMENT ON COLUMN public.gradebook_columns.group_id IS
  'The gradebook_column_groups row this column belongs to, or NULL for an ungrouped column. Must be a group in the same gradebook (composite foreign key).';

-- ON DELETE SET NULL (group_id): deleting a group ungroups its columns rather than deleting them,
-- and leaves gradebook_id alone (which is NOT NULL and part of the key).
ALTER TABLE public.gradebook_columns
  ADD CONSTRAINT gradebook_columns_group_fkey FOREIGN KEY (gradebook_id, group_id)
    REFERENCES public.gradebook_column_groups (gradebook_id, id) ON DELETE SET NULL (group_id);

CREATE INDEX gradebook_columns_group_id_idx ON public.gradebook_columns (group_id) WHERE group_id IS NOT NULL;

